#!/usr/bin/env python3
"""Generate docs/images.md, the list of every container image a pod runs.

The source of truth is the digest pins in platform/group_vars/all/10-infrastructure.yml,
the same values the playbooks deploy. This page is generated from them so that it cannot
describe an image the pod does not run.

    tools/gen-images-doc.py           rewrite docs/images.md
    tools/gen-images-doc.py --check   fail if docs/images.md does not match the pins
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PINS = ROOT / "platform" / "group_vars" / "all" / "10-infrastructure.yml"
DOC = ROOT / "docs" / "images.md"

# What each pinned image does on a pod, and where it comes from. A pin with no entry
# here fails the generator, so a new image cannot ship undocumented.
ROLES = {
    "zenoh": ("The pen: the pod's local Zenoh router, which every arm connects to",
              "Eclipse Zenoh upstream image"),
    "audit": ("Audit subscriber: records what the pod allowed through",
              "GOAT audit subscriber image"),
    "udp_ingest": ("Listens for UDP sensor feeds and publishes them to the pen",
                   "`arms/udp-ingest`"),
    "tcp_ingest": ("Listens for TCP sensor streams (newline, length-prefix or raw framing) "
                   "and publishes them to the pen", "`arms/tcp-ingest`"),
    "tcp_connect": ("Dials sensors that serve their own TCP stream, reconnects, and "
                    "publishes to the pen", "`arms/tcp-connect`"),
    "health_pub": ("Publishes the pod's health to the pen; the uplink bridge carries it to "
                   "the fabric only if released",
                   "`arms/health-pub`"),
    "uplink_bridge": ("Republishes allowed pen keys to the fabric under the pod's slot, "
                      "outbound only", "`arms/uplink-bridge`"),
    "egress": ("Sends released feeds to each declared destination, behind the downlink gate",
               "`arms/egress`"),
    "sapient": ("SAPIENT session arm: BSI Flex 335 v2.0 over TCP",
                "`arms/sapient`"),
}

PIN = re.compile(r'^(?P<var>[a-z_]+)_image_upstream:\s*"(?P<ref>[^"]+)"\s*(?:#\s*(?P<note>.*))?$')


def pins():
    found = []
    for line in PINS.read_text().splitlines():
        m = PIN.match(line)
        if m:
            found.append((m["var"], m["ref"], (m["note"] or "").strip()))
    if not found:
        sys.exit(f"gen-images-doc: no *_image_upstream pins found in {PINS}")
    return found


def render():
    rows = []
    for var, ref, note in pins():
        if var not in ROLES:
            sys.exit(f"gen-images-doc: {var}_image_upstream has no ROLES entry in {__file__}")
        name, _, digest = ref.partition("@")
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", digest):
            sys.exit(f"gen-images-doc: {var}_image_upstream is not pinned by digest: {ref}")
        role, source = ROLES[var]
        version = note.split(",", 1)[0].strip() or "-"
        rows.append(f"| `{name}` | {role} | {source} | `{version}` | `{digest}` |")
    return "\n".join([
        "<!-- Generated by tools/gen-images-doc.py from "
        "platform/group_vars/all/10-infrastructure.yml. Do not edit. -->",
        "",
        "# Container Images",
        "",
        "Every container a pod runs is pinned by digest. A digest names the exact bytes of",
        "an image, so a pod runs the same image whichever registry or carried bundle serves",
        "it. This page lists the images the current source deploys. It is generated from",
        "the pins in `platform/group_vars/all/10-infrastructure.yml`, and CI fails if it",
        "does not match them.",
        "",
        "| Image | Role on the pod | Source | Version | Digest |",
        "| --- | --- | --- | --- | --- |",
        *rows,
        "",
        "## Check What a Pod Runs",
        "",
        "Compare the digests on a pod with this list:",
        "",
        "```bash",
        "sudo podman ps --format '{{.Image}}'",
        "```",
        "",
        "Images built from `arms/` are published by `.github/workflows/images.yml` on every",
        "push to `main`. The workflow attaches a signed build provenance attestation to each",
        "multi-architecture index it publishes. Verify one with the GitHub CLI, using a",
        "reference from the table:",
        "",
        "```bash",
        "gh attestation verify oci://<image>@<digest> --repo <owner>/octo-pod",
        "```",
        "",
        "An image pinned before the workflow attached attestations has none, and the command",
        "reports that no attestation was found. Its digest still identifies it exactly.",
        "",
        "A release does not change pins. A new pin reaches a pod only when an operator",
        "upgrades to a release that contains it. See [Upgrades](upgrading.md).",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/images.md is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not DOC.is_file() or DOC.read_text() != text:
            sys.exit("docs/images.md does not match the image pins; run tools/gen-images-doc.py")
        print(f"docs/images.md matches {len(pins())} pinned images")
        return
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)} ({len(pins())} images)")


if __name__ == "__main__":
    main()
