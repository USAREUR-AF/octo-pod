"""Draw the repository's figures from facts in the tree.

    python3 -I docs/figures/make-figures.py           # write docs/figures/*.svg
    python3 -I docs/figures/make-figures.py --check   # exit 1 if a committed figure is out of date

Each figure is written twice, `<name>-light.svg` and `<name>-dark.svg`, for a
`<picture>` element. Every label in a figure is checked against the file it
comes from (README.md, docs/images.md, docs/faq.md, docs/operations.md), and the
script refuses to draw if one is missing there. The output is deterministic.
Standard library only.
"""

